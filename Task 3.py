import requests
from bs4 import BeautifulSoup
import pandas as pd
import json
import time

def scrape_quotes(pages=5):

    base_url = "https://quotes.toscrape.com/page/{}/"

    records = []

    headers = {
        "User-Agent": "Mozilla/5.0"
    }

    for page in range(1, pages + 1):

        url = base_url.format(page)

        print("Scraping:", url)

        try:
            response = requests.get(
                url,
                headers=headers,
                timeout=10
            )

            response.raise_for_status()

            soup = BeautifulSoup(
                response.text,
                "html.parser"
            )

            quotes = soup.find_all(
                "div",
                class_="quote"
            )

            for quote in quotes:

                text = quote.find(
                    "span",
                    class_="text"
                ).get_text(strip=True)

                author = quote.find(
                    "small",
                    class_="author"
                ).get_text(strip=True)

                tags = [
                    tag.get_text(strip=True)
                    for tag in quote.find_all(
                        "a",
                        class_="tag"
                    )
                ]

                records.append({
                    "quote": text,
                    "author": author,
                    "tags": ", ".join(tags)
                })

            # Rate limiting
            time.sleep(1)

        except requests.RequestException as e:

            print("Request failed:", e)

    return records

data = scrape_quotes(5)

print("Total records:", len(data))

df = pd.DataFrame(data)

