from collections import Counter

all_tags = []

for tags in df["tags"]:
    all_tags.extend(
        [tag.strip() for tag in tags.split(",")]
    )

tag_counts = Counter(all_tags)

print("Most common tags:")

for tag, count in tag_counts.most_common(10):
    print(tag, ":", count)

summary = {
    "total_quotes": len(df),
    "unique_authors": int(df["author"].nunique()),
    "unique_tags": len(tag_counts),
    "top_author": (
        df["author"].value_counts().index[0]
        if len(df) > 0
        else None
    ),
    "top_tag": (
        tag_counts.most_common(1)[0][0]
        if tag_counts
        else None
    )
}

print(json.dumps(summary, indent=4))

with open(
    "scraping_analysis_report.json",
    "w"
) as file:

    json.dump(
        summary,
        file,
        indent=4
    )

